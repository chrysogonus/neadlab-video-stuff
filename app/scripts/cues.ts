#!/usr/bin/env bun
// Writes projects/<id>/cues.md from the project's cue sheet (data/cues.json) resolved against its data — the
// document is generated, so it always shows the times the renderer uses.
//   bun scripts/cues.ts [--project <id>]            (write)
//   bun scripts/cues.ts [--project <id>] --check    (fail if the file is stale)
// Without --project: every project that has a cue sheet.
import path from 'node:path';
import { Lyrics } from '../src/engine/lyrics';
import { AudioData } from '../src/engine/audio';
import { resolveCues, resolveEntries, type CueSheet, type ResolvedCue } from '../src/engine/cues';
import { ROOT, loadProjects, loadSheet, loadStyle, project } from './projects';

const argv = process.argv.slice(2);
const pi = argv.indexOf('--project');
const ids = pi >= 0 ? [project(argv[pi + 1]).id] : Object.keys(loadProjects()).filter((id) => loadSheet(id));
let stale = 0;

for (const id of ids) {
  const sheet = loadSheet(id);
  if (!sheet) throw new Error(`projects/${id} has no data/cues.json`);
  const out = path.join(ROOT, 'projects', id, 'cues.md');
  const md = await doc(id, sheet);
  if (argv.includes('--check')) {
    const cur = await Bun.file(out).text().catch(() => '');
    if (cur !== md) { console.error(`${out} is stale: run bun scripts/cues.ts --project ${id}`); stale++; }
    else console.log(`${out} is up to date`);
  } else {
    await Bun.write(out, md);
    console.log(`wrote ${out}`);
  }
}
if (stale) process.exit(1);

async function doc(id: string, sheet: CueSheet) {
  const p = project(id);
  const ly = new Lyrics(await Bun.file(path.join(ROOT, p.data, 'lyrics.json')).json());
  const aj = await Bun.file(path.join(ROOT, p.data, 'audio.json')).json();
  const au = new AudioData(aj);
  const cues = resolveCues(ly, au, sheet, Object.keys(loadStyle(id).palettes));
  const entries = resolveEntries(ly, au, sheet, cues);
  const s = (x: number) => x.toFixed(2);
  const bar = (t: number) => (au.barAt(t) + 1).toFixed(2); // 1-based bars for reading
  const esc = (x: string) => x.replace(/\|/g, '\\|');
  const anchor = (c: ResolvedCue) =>
    'word' in c.def.anchor ? `"${c.def.anchor.word}" ${s(c.at)}` : `downbeat ${c.def.anchor.bar} (${s(c.at)})`;

  let md = `# ${p.title} — cue sheet

Generated by \`bun scripts/cues.ts\` from [\`data/cues.json\`](data/cues.json) resolved against \`data/\`
(${aj.grid} beat grid, ${au.beats.length} beats, mean ${au.bpm.toFixed(2)} BPM; ${ly.lines.length} sung lines).
Do not edit by hand. Times in seconds of the master; bars are 1-based (bar 1 = the first downbeat, ${s(au.downbeats[0]!)} s).

**How times resolve.** A lyric cue names its line's exact text and, when that text repeats, which occurrence
(0-based); the resolver fails the build on a missing, ambiguous or out-of-range line, an anchor word that is not in
the line, a cue outside its section, or a sung line with no cue. Instrumental cues name a span (downbeats or the
edges of other cues). An entry's cut is one of: on the last beat at or before its first phrase (unless the previous
line is still being sung there — then the phrase boundary), at a phrase's first word, on a downbeat, or when a
line ends.

## Edit

| entry | module | start | end | dur | cut | bars |
|---|---|---:|---:|---:|---|---|
`;
  for (const e of entries) {
    const cut = e.def.cut.at === 'zero' ? 'song start' : e.def.cut.at === 'bar' ? `downbeat ${e.def.cut.bar}` : `${e.def.cut.at} ${(e.def.cut as { cue: string }).cue}`;
    md += `| \`${e.def.id}\` | \`${e.def.file}\`${e.def.params ? ` ${JSON.stringify(e.def.params)}` : ''} | ${s(e.start)} | ${s(e.end)} | ${s(e.end - e.start)} | ${cut} | ${bar(e.start)}–${bar(e.end)} |\n`;
  }
  for (const e of entries) {
    md += `\n## \`${e.def.id}\` — ${s(e.start)}–${s(e.end)} s\n\n`;
    md += `| cue | lyric (occurrence) | span | section | initial → action → result | payoff anchor | palette / region / transition | motif state | assets / notes |\n|---|---|---|---|---|---|---|---|---|\n`;
    for (const c of e.cues) {
      const d = c.def;
      const lyric = d.lyric ? `L${c.line!.i} “${esc(c.line!.text)}”${d.occurrence !== undefined ? ` (#${d.occurrence})` : ''}` : '*(instrumental)*';
      md += `| ${d.id} | ${lyric} | ${s(c.start)}–${s(c.end)} | ${d.section} | ${esc(d.initial)} → ${esc(d.action)} → ${esc(d.result)} | ${anchor(c)} | ${d.palette} / ${d.region} / ${d.transition} | ${esc(d.motif)} | ${esc([...(d.assets ?? []), d.notes ?? ''].filter(Boolean).join('; ')) || '—'} |\n`;
    }
  }
  const inst = [...cues.values()].filter((c) => !c.line).sort((a, b) => a.start - b.start);
  md += `\n## Coverage\n\nEvery sung line has one cue (${ly.lines.length}/${ly.lines.length}); the ${entries.length} entries tile 0–${s(au.duration)} s with no gaps or overlaps.`;
  md += inst.length ? ` Instrumental passages covered: ${inst.map((c) => `${c.id} (${s(c.start)}–${s(c.end)})`).join(', ')}.\n` : '\n';
  return md;
}

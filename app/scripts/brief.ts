#!/usr/bin/env bun
// The facts the pipeline's model steps work from, generated from a project's data (./vid make runs it):
//   projects/<id>/work/agent/brief.md     the song: lines with times and word tokens, sections with energy, the
//                                         instrumental passages, and the formats of style.json and cues.json
//   projects/<id>/work/agent/library.md   the scene library: every lib-* scene's schema
//   bun scripts/brief.ts <id>
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { Lyrics } from '../src/engine/lyrics';
import { AudioData } from '../src/engine/audio';
import { LIBRARY } from '../src/library';
import { REGIONS, TRANSITIONS } from '../src/engine/cues';
import type { ParamSpec } from '../src/engine/schema';
import { ROOT, project } from './projects';

const p = project(process.argv[2]);
const dir = path.join(ROOT, 'projects', p.id, 'work', 'agent');
mkdirSync(dir, { recursive: true });
const aj = await Bun.file(path.join(ROOT, p.data, 'audio.json')).json();
const ly = new Lyrics(await Bun.file(path.join(ROOT, p.data, 'lyrics.json')).json());
const au = new AudioData(aj);
const s2 = (x: number) => x.toFixed(2);
const db = (t: number) => Math.max(0, Math.floor(au.barAt(t + 0.02))); // downbeat index at or before t (0 before the first)
const mean = (a: number, b: number, f: (t: number) => number) => {
  let s = 0, n = 0;
  for (let t = a; t < b; t += 0.1, n++) s += f(t);
  return n ? s / n : 0;
};
const level = (x: number) => (x < 0.2 ? 'quiet' : x < 0.4 ? 'low' : x < 0.6 ? 'mid' : x < 0.8 ? 'high' : 'peak');

function brief() {
  const counts = new Map<string, number>(), seen = new Map<string, number>();
  for (const l of ly.lines) counts.set(l.text, (counts.get(l.text) ?? 0) + 1);
  let md = `# ${p.title}: brief

Generated by \`bun scripts/brief.ts ${p.id}\` from \`projects/${p.id}/data/\`. Times in seconds of the master.

- Kind: ${p.kind}. Duration ${s2(au.duration)} s.
- Tempo: ${au.bpm.toFixed(1)} BPM, ${aj.time_signature ?? 4}/4, ${aj.grid ?? 'constant'} beat grid; ${au.downbeats.length} downbeats (bars), numbered from 0 (downbeat 0 at ${s2(au.downbeats[0]!)} s).
- ${ly.lines.length} sung lines.

## Sections

Energy is the mix loudness (0..1) averaged over the section; vocal is how much singing it holds.

| section | start | end | downbeats | energy | vocal |
|---|---:|---:|---|---|---|
`;
  for (const s of au.sections) {
    const e = mean(s.start, s.end, (t) => au.sample(t).rms), v = mean(s.start, s.end, (t) => au.sample(t).vocal);
    md += `| ${s.name} | ${s2(s.start)} | ${s2(s.end)} | ${db(s.start)}–${db(s.end)} | ${level(e)} (${e.toFixed(2)}) | ${level(v)} |\n`;
  }
  md += `\n## Lines\n\nA lyric cue names its line by \`lyric\` (the exact text below) and, when the text repeats, \`occurrence\` (0-based, shown as #n). Anchor words must be one of the line's word tokens exactly as listed (punctuation included). "bar" is the downbeat index at or before the line's start.\n\n| line | section | start | end | bar | lyric | occurrence | word tokens |\n|---:|---|---:|---:|---:|---|---|---|\n`;
  for (const l of ly.lines) {
    const k = seen.get(l.text) ?? 0;
    seen.set(l.text, k + 1);
    const sec = au.sections.find((s) => l.start >= s.start - 1e-3 && l.start < s.end)?.name ?? '?';
    md += `| ${l.i} | ${sec} | ${s2(l.start)} | ${s2(l.end)} | ${db(l.start)} | ${l.text.replace(/\|/g, '\\|')} | ${counts.get(l.text)! > 1 ? `#${k}` : ''} | ${l.words.map((w) => `\`${w.w}\``).join(' ')} |\n`;
  }
  // instrumental passages: stretches of 3 s or more with no sung line
  const gaps: [number, number][] = [];
  let prev = 0;
  for (const l of ly.lines) { if (l.start - prev >= 3) gaps.push([prev, l.start]); prev = Math.max(prev, l.end); }
  if (au.duration - prev >= 3) gaps.push([prev, au.duration]);
  md += `\n## Instrumental passages (3 s or longer with no singing)\n\n| from | to | dur | downbeats | energy | after line | before line |\n|---:|---:|---:|---|---|---:|---:|\n`;
  for (const [a, b] of gaps) {
    const before = ly.lines.find((l) => l.start >= b - 1e-3), after = [...ly.lines].reverse().find((l) => l.end <= a + 1e-3);
    md += `| ${s2(a)} | ${s2(b)} | ${s2(b - a)} | ${db(a)}–${db(b)} | ${level(mean(a, b, (t) => au.sample(t).rms))} | ${after ? `L${after.i}` : 'start'} | ${before ? `L${before.i}` : 'end'} |\n`;
  }
  md += `\n${FORMATS}`;
  return md;
}

function library() {
  const spec = (k: string, s: ParamSpec) =>
    `\`${k}\` (${s.enum ? s.enum.map((e) => `'${e}'`).join(' | ') : s.type}${s.default === undefined ? ', required' : `, default ${JSON.stringify(s.default)}`}): ${s.description}`;
  let md = `# The scene library

Generated by \`bun scripts/brief.ts\` from the schemas in \`app/src/scenes/lib-*.ts\` (\`app/src/library.ts\`). An entry plays a
library scene by \`"file": "<name>"\`; its \`params\` and its cues' \`params\` are checked against the scene's schema when the
sheet loads (unknown, missing required or mistyped parameters fail). "lyric: own" means the scene draws the sung line itself;
"layer" means the engine's karaoke layer shows it in the lower third and the scene keeps that area quiet.

`;
  for (const [name, s] of Object.entries(LIBRARY)) {
    md += `## ${name}\n\n${s.description}\n\n- kinds: ${s.kinds.join(', ')}; lyric: ${s.lyrics}\n`;
    md += `- entry params: ${Object.entries(s.entry).map(([k, v]) => spec(k, v)).join('; ') || 'none'}\n`;
    md += `- cue params: ${Object.entries(s.cue).map(([k, v]) => spec(k, v)).join('; ') || 'none'}\n`;
    md += `- example: entry \`${JSON.stringify(s.example.entry)}\`, cues \`${JSON.stringify(s.example.cues)}\`\n\n`;
  }
  return md;
}

const FORMATS = `## Formats

### data/style.json

\`\`\`json
{
  "palettes": { "<name>": { "bg": "#RRGGBB", "type": "#RRGGBB", "accent": "#RRGGBB", "accent2": "#RRGGBB (optional)", "dim": "(optional)", "panel": "(optional)", "rule": "(optional)", "onAccent": "(optional: text on accent)" } },
  "fonts": { "display": { "family": "archivo", "width": 100, "weight": 900 }, "body": { "family": "archivo", "width": 100, "weight": 500 },
             "mono": { "family": "mono", "weight": 400 }, "serif": { "family": "serif", "weight": 400, "italic": true } },
  "karaoke": { "palette": "<name>", "font": { "family": "archivo", "width": 100, "weight": 700 }, "size": 64, "minSize": 44,
               "sung": "type", "unsung": "type", "unsungAlpha": 0.32, "active": "accent", "y": 0.86, "scrim": 0.5, "scrimColor": "bg", "next": true }
}
\`\`\`

- Palettes: one or more (e.g. a dark and a light one, or one per act); every palette needs \`bg\`, \`type\` and \`accent\`
  (the library derives the others), and every palette must have the keys the karaoke colours name. \`type\` on \`bg\` needs a
  contrast ratio of at least 7, \`accent\` on \`bg\` at least 3.
- Fonts available: \`archivo\` (a grotesque; \`width\` 62–125 %, \`weight\` 300/500/700/900), \`archivoItalic\` (width 75 or 100,
  weight 400/800), \`serif\` (Cormorant Garamond, weight 400/600, \`italic\`), \`mono\` (IBM Plex Mono, weight 300–700). Roles the
  library uses: \`display\`, \`body\`, \`mono\`, \`serif\`; you may add others for custom scenes.
- \`karaoke\`: the project-wide lyric layer; fields may be omitted (defaults shown). \`false\` turns it off (only if every scene
  draws its own lyric).

### data/cues.json

\`\`\`json
{
  "entries": [ { "id": "open", "file": "lib-title", "cut": { "at": "zero" }, "params": { "title": "…" } },
               { "id": "v1", "file": "lib-field", "cut": { "at": "beat", "cue": "L00" } } ],
  "cues": [ { "id": "L00", "lyric": "<exact line text>", "occurrence": 0, "scene": "v1", "section": "verse1",
              "initial": "what is on screen as the cue starts", "action": "what happens", "result": "what is on screen after",
              "anchor": { "word": "<a word token of the line>" }, "palette": "<palette name>", "region": "full",
              "transition": "cut", "motif": "state of the recurring motif", "params": { } },
            { "id": "intro", "span": ["start", { "cue": "L00", "edge": "start" }], "scene": "open", "section": "intro",
              "initial": "…", "action": "…", "result": "…", "anchor": { "bar": 2 }, "palette": "…", "region": "center",
              "transition": "cut", "motif": "…" } ]
}
\`\`\`

- Entries play in order, each from its cut to the next entry's cut (the last to the end). The first entry cuts at
  \`{"at": "zero"}\`. Other cuts: \`{"at": "beat", "cue": id}\` (the last beat at or before that cue's first word; the usual cut),
  \`{"at": "word", "cue": id}\` (exactly on its first word), \`{"at": "bar", "bar": n}\` (on downbeat n), \`{"at": "end", "cue": id}\`
  (when that cue's line ends).
- Every sung line gets exactly one cue (\`lyric\` + \`occurrence\` when the text repeats). Instrumental passages may get
  cues with a \`span\` ([from, to]: a downbeat index, "start", "end", or \`{"cue": id, "edge": "start"|"end"}\`).
- A cue's \`scene\` is the id of the entry it plays in; its start must fall inside that entry and inside its \`section\`.
- \`anchor\`: the moment the cue's action lands: \`{"word": token}\` (\`"nth"\` if the token repeats in the line) or \`{"bar": n}\`.
- \`region\`: ${REGIONS.join(', ')}; \`transition\`: ${TRANSITIONS.join(', ')}. \`palette\`: a palette of style.json.
- \`params\`: the scene's cue parameters (see library.md); entry \`params\`: the scene's entry parameters.
- A custom scene is an entry whose \`file\` is \`${'<project id>'}-<name>\` (written in a later step as app/src/scenes/<file>.ts).
`;

writeFileSync(path.join(dir, 'brief.md'), brief());
writeFileSync(path.join(dir, 'library.md'), library());
console.log(`wrote ${path.relative(ROOT, dir)}/brief.md and library.md`);
